#!/usr/bin/env python3
"""Backtest: run every input through verifier/verify.py and write backtest/RESULTS.md.

usage: python -I backtest/run_backtest.py [--no-cross]

Sets (all run through verify.py as a subprocess, exactly as the server calls it):
  A. True positives: ARVO's crashing input for each of the 6 confirmed libucl cases, with its own --case.
  B. Hand-made fakes (test-inputs/fake/hand_made_*), against the default case 42482847.
  C. Real bug inputs submitted against a DIFFERENT case (every ARVO input x every other case).
     These show what the control run really measures. Skipped with --no-cross.

Money per verdict: reproduced -> bond returned ($0 settled); inconclusive -> bond returned;
not_reproduced -> bond forfeited ($0.25 settled).
A "failure" is any run where verify.py did not print exactly one valid JSON line, exited non-zero,
or took longer than 60 s.
"""
import datetime, hashlib, json, os, platform, subprocess, sys, time

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
VERIFY = os.path.join(REPO, "verifier", "verify.py")
INPUTS = os.path.join(REPO, "targets", "libucl", "inputs")
FAKES = os.path.join(REPO, "test-inputs", "fake")
OUT = os.path.join(HERE, "RESULTS.md")
DEFAULT_CASE = "42482847"
CASES = ["42482847", "42482848", "42486194", "42490132", "42497487", "42512369"]
VERDICTS = ("reproduced", "not_reproduced", "inconclusive")


def rel(p):
    return os.path.relpath(p, REPO).replace("\\", "/")


def run_verify(path, case):
    t = time.time()
    try:
        p = subprocess.run([sys.executable, "-I", VERIFY, path, "--case", case],
                           capture_output=True, text=True, timeout=75)
    except subprocess.TimeoutExpired:
        return {"verdict": None, "detail": "", "failure": "verify.py exceeded 75 s (killed)", "secs": 75.0}
    dt = round(time.time() - t, 1)
    lines = p.stdout.splitlines()
    failure = None
    obj = {}
    try:
        obj = json.loads(lines[0]) if len(lines) == 1 else {}
    except ValueError:
        obj = {}
    if len(lines) != 1 or set(obj) != {"verdict", "detail"} or obj.get("verdict") not in VERDICTS:
        failure = f"bad stdout: {p.stdout[:200]!r} stderr: {p.stderr[-200:]!r}"
    elif p.returncode != 0:
        failure = f"exit code {p.returncode}"
    elif dt > 60:
        failure = f"took {dt}s (> 60 s cap)"
    return {"verdict": obj.get("verdict"), "detail": obj.get("detail", ""), "failure": failure, "secs": dt}


def money(verdict):
    return {"reproduced": "returned", "inconclusive": "returned", "not_reproduced": "FORFEITED"}.get(verdict, "-")


def sh(cmd):
    try:
        return subprocess.run(cmd, capture_output=True, text=True, timeout=30).stdout.strip()
    except Exception:
        return "?"


def main():
    cross = "--no-cross" not in sys.argv
    started = datetime.datetime.now().astimezone()
    rows = []  # (set, label, input, case, result)

    for c in CASES:
        path = os.path.join(INPUTS, f"arvo_{c}.poc")
        rows.append(("A", f"ARVO {c} (real bug)", path, c, None))
    for name in sorted(os.listdir(FAKES)):
        if name.startswith("hand_made_"):
            rows.append(("B", f"{name} (HAND-MADE fake)", os.path.join(FAKES, name), DEFAULT_CASE, None))
    if cross:
        for p in CASES:
            for c in CASES:
                if p != c:
                    rows.append(("C", f"ARVO {p} input vs case {c}", os.path.join(INPUTS, f"arvo_{p}.poc"), c, None))

    results = []
    for i, (s, label, path, case, _) in enumerate(rows, 1):
        r = run_verify(path, case)
        results.append((s, label, path, case, r))
        print(f"[{i}/{len(rows)}] {s} {label} --case {case}: {r['verdict']} ({r['secs']}s)"
              + (f" FAILURE: {r['failure']}" if r["failure"] else ""), flush=True)

    def count(set_name):
        rs = [r for s, *_, r in results if s == set_name]
        c = {v: sum(1 for r in rs if r["verdict"] == v and not r["failure"]) for v in VERDICTS}
        c["failures"] = sum(1 for r in rs if r["failure"])
        c["total"] = len(rs)
        return c

    A, B, C = count("A"), count("B"), count("C")
    wrongly_forfeited = A["not_reproduced"]          # real bug on its own case, bond forfeited
    fake_refunded_as_bug = B["reproduced"]           # fake that the sandbox called a bug
    all_secs = [r["secs"] for *_, r in results]
    finished = datetime.datetime.now().astimezone()

    L = []
    w = L.append
    w("# Backtest results")
    w("")
    w(f"Generated by `python -I backtest/run_backtest.py` on {finished:%Y-%m-%d %H:%M %Z}. Do not edit by hand.")
    w("")
    w(f"- Commit: `{sh(['git', '-C', REPO, 'rev-parse', '--short', 'HEAD'])}`"
      f"{' (working tree had uncommitted changes)' if sh(['git', '-C', REPO, 'status', '--porcelain']) else ''}")
    w(f"- verify.py sha256: `{hashlib.sha256(open(VERIFY, 'rb').read()).hexdigest()}`")
    w(f"- Host: {platform.system()} {platform.release()} {platform.machine()}, Python {platform.python_version()}, "
      f"Docker {sh(['docker', 'version', '--format', '{{.Server.Version}}'])}")
    w(f"- Runs: {len(results)} verify.py calls, {min(all_secs)}-{max(all_secs)} s each, "
      f"{(finished - started).total_seconds():.0f} s total")
    w("")
    w("## Headline counts")
    w("")
    w("| Set | Inputs | reproduced (bond returned) | not_reproduced (bond forfeited) | inconclusive (bond returned) | failures |")
    w("|---|---|---|---|---|---|")
    w(f"| A. Real bugs, own case | {A['total']} | {A['reproduced']} | {A['not_reproduced']} | {A['inconclusive']} | {A['failures']} |")
    w(f"| B. Hand-made fakes, default case {DEFAULT_CASE} | {B['total']} | {B['reproduced']} | {B['not_reproduced']} | {B['inconclusive']} | {B['failures']} |")
    if cross:
        w(f"| C. Real bug inputs vs a different case | {C['total']} | {C['reproduced']} | {C['not_reproduced']} | {C['inconclusive']} | {C['failures']} |")
    w("")
    w(f"- **Wrongly forfeited real bugs (set A, not_reproduced): {wrongly_forfeited} of {A['total']}.**")
    w(f"- **Hand-made fakes judged reproduced (set B): {fake_refunded_as_bug} of {B['total']}.**")
    w(f"- **Failures (no valid verdict, non-zero exit, or > 60 s): {A['failures'] + B['failures'] + C['failures']}.**")
    w("")
    w("## What these numbers do and do not show")
    w("")
    w("- **Set A is in-sample.** These are ARVO's own crashing inputs for the cases verify.py was built and tested on. "
      "6/6 shows the pipeline works end to end; it is not evidence about unseen real-world reports.")
    w("- **Set B is hand-made by us**, not real spam. These inputs are easy (they don't crash the parser at all). "
      "This backtest does not show that spam is stopped, and we make no such claim.")
    w("- **The control run is weaker than one commit per bug.** ARVO's fixed images are a later libucl version where the "
      "crash no longer happens, not each bug's exact fix commit. Five of the six fixed images are the same libucl commit "
      "`45997ad` (2022-01-06), and the sixth (42512369) is `8a0294f` (2025-06-04). The 42482847 and 42482848 vulnerable images "
      "are the same libucl commit (`875c251`). So `reproduced` means \"this input triggers the expected ASan error in "
      "libucl code on the pinned vulnerable build, and the crash is gone in a later libucl\". Set C shows this: real bug "
      "inputs give `reproduced` on other cases whose vulnerable build also has that bug.")
    if cross:
        w(f"- **Set C has {C['not_reproduced']} real-bug inputs that were forfeited.** In each, the chosen case's "
          "vulnerable build ran the input clean 3/3, so that build does not show the bug. A real bug submitted against "
          "the wrong pinned build loses its bond. We did not check why each build is clean (for example, whether the bug "
          "was added in a later commit). These are not counted as \"wrongly forfeited\", because the headline counts "
          "only bugs submitted against their own case.")
    w("- **A fixed image is not bug-free.** ARVO 42512369's input still gives a heap-buffer-overflow at "
      "`ucl_hash_search src/ucl_hash.c:460` on the `45997ad` fixed build (checked directly with "
      "`harness/arvo_case_check.py`'s runner, 2026-11-16).")
    w("- **Each verdict uses only one expected error type per case** (heap-buffer-overflow for all six). A real crash of "
      "another type (for example the SEGV rows in set C) is `inconclusive`: the bond is returned, but the bug is not "
      "credited as reproduced.")
    w("")
    w("## Demo edge cases: what we could and could not produce")
    w("")
    both = [x for x in results if "crashes on both builds" in x[4]["detail"]]
    mixed = [x for x in results if x[4]["verdict"] == "inconclusive" and "vul run" in x[4]["detail"]
             and len({part.split(": ", 1)[1] for part in x[4]["detail"].split(": ", 1)[1].split("; ")
                      if ": " in part}) > 1]
    if both:
        w(f"- **Crash on both builds: produced {len(both)} time(s)** in this run: "
          + ", ".join(f"{x[1]} --case {x[3]}" for x in both) + ".")
    else:
        w(f"- **Crash on both builds: NOT produced** in this run ({C['total']} cross-case pairs searched). The one input "
          "known to crash a `45997ad` fixed build (ARVO 42512369) gives a SEGV, not a heap-buffer-overflow, on every older "
          "vulnerable build, so verify.py stops at `inconclusive` (wrong error type) before the control run. We did not "
          "fabricate one.")
    if mixed:
        w(f"- **Mixed result across the 3 vulnerable runs: produced {len(mixed)} time(s)**: "
          + ", ".join(f"{x[1]} --case {x[3]}" for x in mixed) + ".")
    else:
        w("- **Mixed or flaky result: NOT produced.** No input in this run gave different results across its vulnerable "
          "runs. libucl's parser is single-threaded and deterministic on a given input, so we do not expect flakiness "
          "here. We did not fabricate one.")
    w("- **Real inconclusive that we did produce:** a real bug input with the wrong error type for the case "
      "(ARVO 42512369 input against any other case: SEGV in `kh_get_ucl_hash_caseless_node`, 3/3).")
    w("")
    for set_name, title in (("A", "A. Real bugs, each with its own case"),
                            ("B", f"B. Hand-made fakes (labeled HAND-MADE), default case {DEFAULT_CASE}"),
                            ("C", "C. Real bug inputs against a different case")):
        sel = [x for x in results if x[0] == set_name]
        if not sel:
            continue
        w(f"## {title}")
        w("")
        w("| Input | Case | Verdict | Bond | Time | Detail |")
        w("|---|---|---|---|---|---|")
        for _, label, path, case, r in sel:
            verdict = r["verdict"] if not r["failure"] else f"FAILURE ({r['verdict']})"
            detail = (r["failure"] or r["detail"]).replace("|", "\\|")
            w(f"| `{rel(path)}` {label} | {case} | {verdict} | {money(r['verdict']) if not r['failure'] else '-'} "
              f"| {r['secs']}s | {detail} |")
        w("")
    w("## Not verified")
    w("")
    w("- Live payments: this backtest calls verify.py directly; no x402 deposit or settle was made.")
    w("- An input that genuinely hangs libucl (the timeout path was tested with a lowered cap in verifier/test_verify.py).")
    w("- The four ARVO libucl cases that crash in bundled headers (42487344, 42495584, 42501732, 42501839): not pulled.")
    w("- Concurrency and repeated load. Every call here ran one after another on one Windows machine.")
    w("")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(L))
    print(f"\nA {A}\nB {B}\nC {C}\nwrongly_forfeited={wrongly_forfeited} fakes_reproduced={fake_refunded_as_bug}"
          f"\nwrote {rel(OUT)}")
    sys.exit(1 if (A["failures"] + B["failures"] + C["failures"]) else 0)


if __name__ == "__main__":
    main()
